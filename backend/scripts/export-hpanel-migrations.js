const { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } = require('fs');
const { join } = require('path');

const prismaDir = join(__dirname, '..', 'prisma');
const migrationsDir = join(prismaDir, 'migrations');
const exportDir = join(prismaDir, 'hpanel-migrations');
const migrationNames = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

mkdirSync(exportDir, { recursive: true });

const expectedCopies = new Set(migrationNames.map((name) => `${name}.sql`));
const staleCopies = readdirSync(exportDir)
  .filter((name) => name.endsWith('.sql') && !expectedCopies.has(name));
if (staleCopies.length) {
  throw new Error(`Remove obsolete HPanel migration copies from the source history: ${staleCopies.join(', ')}`);
}

for (const migrationName of migrationNames) {
  const source = join(migrationsDir, migrationName, 'migration.sql');
  const destination = join(exportDir, `${migrationName}.sql`);
  const sql = readFileSync(source);

  copyFileSync(source, destination);
  if (!readFileSync(destination).equals(sql)) {
    throw new Error(`HPanel SQL export did not match Prisma migration: ${migrationName}`);
  }
}

const exportReadme = [
  '# HPanel SQL migration copies',
  '',
  'These files are exact copies of `../migrations/*/migration.sql`, generated by `npm run hpanel:export`.',
  'The Prisma migration directory is the source of truth. After adding or changing a migration, run the export command',
  'and include the matching copy in the same change.',
  '',
  'For a new database, use `../hostinger-bootstrap.sql` once instead of importing these files one by one.',
  'For an existing database, the normal deployment is `npm run migrate:deploy`. Only if applying SQL manually in',
  'phpMyAdmin, import each pending migration copy once, in filename order, then run',
  '`npx prisma migrate resolve --applied <migration-name>` from the backend directory for each manually applied',
  'migration. Never re-import an already-applied migration or the fresh-database bootstrap into an existing database.',
  '',
].join('\n');

writeFileSync(join(exportDir, 'README.md'), exportReadme);
console.log(`Exported ${migrationNames.length} HPanel SQL migration copies to ${exportDir}`);
